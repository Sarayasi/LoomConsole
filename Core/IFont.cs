    public bool Bit(char c, int x, int y)
{
    if ((uint)x >= (uint)W || (uint)y >= (uint)H) return false;
    int idx = c - 32;
    if ((uint)idx >= 95) return false;
    byte row = Glyphs[idx * 5 + y];
    // x=0 → bit 2 (izquierda), x=2 → bit 0 (derecha)
    return ((row >> (W - 1 - x)) & 1) != 0;
}
